create table if not exists public.reportes (
  id bigint generated by default as identity primary key,
  nombre text not null default 'Anónimo',
  colonia text not null,
  descripcion text not null,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  foto_url text,
  created_at timestamptz not null default now()
);
create table if not exists public.residuos (
  id bigint generated by default as identity primary key,
  local_id text unique not null,
  tipo text not null,
  descripcion text not null,
  colonia text not null,
  lat double precision not null check (lat between -90 and 90),
  lng double precision not null check (lng between -180 and 180),
  responsable text,
  foto_url text,
  estado text not null default 'pendiente',
  recorded_at timestamptz not null default now(),
  created_at timestamptz not null default now()
);

alter table public.reportes enable row level security;
alter table public.residuos enable row level security;
drop policy if exists "reportes lectura pública" on public.reportes;
drop policy if exists "reportes envío público" on public.reportes;
drop policy if exists "residuos lectura pública" on public.residuos;
drop policy if exists "residuos envío público" on public.residuos;
drop policy if exists "residuos reintento propio por local_id" on public.residuos;
create policy "reportes lectura pública" on public.reportes for select to anon, authenticated using (true);
create policy "reportes envío público" on public.reportes for insert to anon, authenticated with check (
  length(colonia) between 1 and 120 and length(descripcion) between 1 and 2000
);
create policy "residuos lectura pública" on public.residuos for select to anon, authenticated using (true);
create policy "residuos envío público" on public.residuos for insert to anon, authenticated with check (
  length(tipo) between 1 and 100 and length(descripcion) between 1 and 2000 and length(colonia) between 1 and 120
);
-- Necesario para reintentar un registro local con el mismo local_id.
create policy "residuos reintento propio por local_id" on public.residuos for update to anon, authenticated using (true) with check (true);

insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('reportes','reportes',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=true, file_size_limit=5242880, allowed_mime_types=array['image/jpeg','image/png','image/webp'];
insert into storage.buckets (id, name, public, file_size_limit, allowed_mime_types)
values ('residuos','residuos',true,5242880,array['image/jpeg','image/png','image/webp'])
on conflict (id) do update set public=true, file_size_limit=5242880, allowed_mime_types=array['image/jpeg','image/png','image/webp'];
drop policy if exists "subir fotos reportes" on storage.objects;
drop policy if exists "actualizar fotos residuos" on storage.objects;
drop policy if exists "ver fotos públicas ecomapa" on storage.objects;
create policy "subir fotos reportes" on storage.objects for insert to anon, authenticated with check (
  bucket_id in ('reportes','residuos') and lower(storage.extension(name)) in ('jpg','jpeg','png','webp')
);
create policy "actualizar fotos residuos" on storage.objects for update to anon, authenticated using (bucket_id='residuos') with check (bucket_id='residuos');
create policy "ver fotos públicas ecomapa" on storage.objects for select to anon, authenticated using (bucket_id in ('reportes','residuos'));

